"""Collect a controlled-comparison scene folder into tables, CSVs and training-curve plots.

    PYTHONPATH=src python scripts/fair_report.py --root results/hypernerf/slice-banana
reads  <root>/fair/runs/*/metrics.json (+ curve.csv), <root>/fair/baselines/metrics.json, logs/stage1_<scene>.log
writes <root>/fair/{tables.md, summary.json, curves.csv, stage1_curve.csv, curve_val.png, curve_test.png,
       curve_stage1.png, per_time_psnr.png}
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import re

import numpy as np

FULL = ["psnr", "psnr_img", "ssim", "lpips"]
DYN = ["dyn_psnr", "dyn_ssim", "dyn_lpips"]
PREC = {"psnr": 2, "psnr_img": 2, "ssim": 4, "lpips": 4, "dyn_psnr": 2, "dyn_ssim": 4, "dyn_lpips": 4}


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def row(r, keys):
    return " | ".join(f"{r[k]:.{PREC[k]}f}" if k in r else "–" for k in keys)


def per_time(res):
    out = {}
    for r in res["per_image"]:
        out.setdefault(round(r["fid"], 4), []).append(r["psnr"])
    return {k: float(np.mean(v)) for k, v in sorted(out.items())}


def read_curve(p):
    with open(p) as f:
        return [{k: float(v) for k, v in r.items()} for r in csv.DictReader(f)]


def stage1_curve(log):
    rows = {}
    pat = re.compile(r"\[ITER (\d+)\] Evaluating (test|train): L1 [0-9.e-]+ PSNR ([0-9.]+)")
    for line in open(log, errors="ignore"):
        m = pat.search(line)
        if m:
            rows.setdefault(int(m.group(1)), {})[m.group(2)] = float(m.group(3))
    return [{"iter": k, "train_psnr": v.get("train"), "test_psnr": v.get("test")} for k, v in sorted(rows.items())]


SRC = {"slice-banana": "/data/HyperNeRF/interp/slice-banana", "cut-lemon1": "/data/HyperNeRF/interp/cut-lemon1",
       "chickchicken": "/data/HyperNeRF/interp/chickchicken", "keyboard": "/data/HyperNeRF/misc/keyboard",
       "split-cookie": "/data/HyperNeRF/misc/split-cookie", "vrig-3dprinter": "/data/HyperNeRF/vrig/3dprinter"}
PAPER = {  # ODE-GS (ICLR'26) Table 3, HyperNeRF: (PSNR, SSIM, LPIPS)
    "slice-banana": {"ODE-GS": (21.29, .6437, .3230), "Deformable-GS": (21.73, .6530, .3241)},
    "cut-lemon1": {"ODE-GS": (21.69, .6964, .3098), "Deformable-GS": (21.36, .6950, .3207)},
    "chickchicken": {"ODE-GS": (20.29, .7254, .3023), "Deformable-GS": (19.03, .6996, .3167)},
    "split-cookie": {"ODE-GS": (20.72, .6593, .2406), "Deformable-GS": (17.84, .5698, .2945)},
    "keyboard": {"ODE-GS": (21.06, .7399, .2327), "Deformable-GS": (19.98, .6957, .2497)},
    "vrig-3dprinter": {"ODE-GS": (20.22, .6946, .2242), "Deformable-GS": (19.89, .6775, .2378)},
}


def write_report(root, scene, F, table_lines, runs, base):
    info = load(os.path.join(F, "configs", "scene.json")) or {}
    s1 = stage1_curve(f"logs/stage1_{scene}.log") if os.path.exists(f"logs/stage1_{scene}.log") else []
    masks = sorted(os.path.basename(p) for p in glob.glob(os.path.join(F, "masks_*.png")))
    test = {n: r["results"]["rollout" if r["method"] == "jepa" else "default"] for n, r in runs.items() if r["split"] == "full"}
    dnerf = info.get("dataset") == "dnerf" or "/dnerf/" in f"/{root}/"
    ts, ic = (0.8, 0.64) if dnerf else (0.9, 0.8)
    ode = next((r["cfg"] for r in runs.values() if r["method"] == "odegs"), {})
    jc = next((r["cfg"] for r in runs.values() if r["method"] == "jepa"), {})
    dt = info.get("dt", float("nan"))
    obs = (jc.get("context_len", 30) - 1) * jc.get("context_stride", 1) * dt
    hor = jc.get("max_horizon", 0) * dt
    data_line = (f"- Data: `/data/D-NeRF/{scene}` (Blender format, black background, 800×800). Train + test cameras are pooled, "
                 "as in ODE-GS protocol B." if dnerf else
                 f"- Data: `{SRC.get(scene, scene)}`, read by ODE-GS `readNerfiesCameras`, which picks cameras "
                 "and resolution from the parent folder: interp = ids[::4] + ids[2::4] at rgb/2x, misc = all ids at rgb/2x, "
                 "vrig = train + val ids at rgb/4x. fid = time_id / max.")
    lines = [f"# {'D-NeRF' if dnerf else 'HyperNeRF'} {scene}: controlled stage-2 comparison (4DGS-JEPA vs ODE-GS, shared Stage 1)", "",
             "_Auto-generated by `scripts/fair_report.py --write_report`; numbers are seed 0, last checkpoint._", "",
             "## Scene and protocol", "",
             data_line,
             f"- Protocol B with time_split {ts}: cameras are sorted by time and the first {ts:.0%} form the prefix. "
             f"Prefix: {info.get('prefix_cams', '?')} cameras / {info.get('prefix_times', '?')} times, last t = {info.get('last_prefix_t', float('nan')):.4f}. "
             f"Test: {info.get('eval_cams', '?')} cameras, t ≥ {info.get('first_eval_t', float('nan')):.4f}. Image size {info.get('image_hw', '?')} (H, W). "
             f"Frame spacing dt = {dt:.6f}.",
             f"- Shared Stage 1: Deformable-GS trained by ODE-GS `train_interpolation.py --time_split {ts}{' --is_blender' if dnerf else ''}` "
             f"with ODE-GS defaults (40k iterations, as in the paper), {info.get('num_gaussians', '?')} Gaussians"
             + (f". Final Stage-1 PSNR: prefix (train) cameras {s1[-1]['train_psnr']:.2f}, t > {ts} cameras queried {s1[-1]['test_psnr']:.2f}." if s1 else "."),
             "  Every method below starts from it: Deformable-GS query, static, constant velocity, ODE-GS and JEPA.",
             f"- Inner split, used for the held-out validation curves, the CV window{'' if dnerf else ' and the LR decision'}: stage 2 sees Stage-1 states with "
             f"t ≤ {ic} only and is scored on the prefix cameras with {ic} < t ≤ prefix end. Test-camera numbers never drive a decision.",
             "- Controlled stage 2. These are identical for JEPA and ODE-GS: optimizer steps (90k), Gaussian samples per step (4096), "
             f"observation points (the same 30 Stage-1 time points, span ≈ {obs:.3f}), training horizon (≈ {hor:.3f}), AdamW with "
             "LR 1e-3, weight decay 1e-4, 5% warmup then cosine to 0.01×, grad clip 1.0, seed 0, and the last checkpoint. "
             "Parameter counts differ by 5% (JEPA 4.08M vs ODE-GS 3.88M). "
             + ("Settings are the HyperNeRF ones unchanged, except that the training horizon is the D-NeRF test range (0.2, "
                "ODE-GS's own D-NeRF max_extrap_time_span) instead of 0.1." if dnerf else
                "The LR (1e-3, rather than the earlier 3e-4) was chosen on slice-banana's inner split, where ODE-GS gained "
                "0.54 dB with 1e-3; see the slice-banana report."),
             "- Inherent differences (method design, not tuned): JEPA's loss is latent prediction (EMA teacher) + composition + geometry "
             "decoding with 4 targets per context. ODE-GS uses an L1 trajectory loss on 10 targets plus its adaptive derivative "
             f"regulariser ({'D-NeRF' if dnerf else 'HyperNeRF'} config: reg_weight {ode.get('reg_weight', '?')}, "
             f"temperature {ode.get('reg_temperature', '?')}, xyz_reg {ode.get('xyz_reg_weight', '?')}).",
             "- Dynamic-region metrics: the mask is computed once per scene, identically for all methods. It keeps pixels where "
             "max_c |GT_t − R_t0| > 0.2, with R_t0 the Stage-1 render of the static state at the forecast origin from the same "
             "camera, then applies opening (radius 2) and dilation (4 px). It marks where the scene changed, so it penalises "
             "Static by construction. dyn PSNR = PSNR over mask pixels; dyn SSIM / LPIPS = SSIM map / spatial LPIPS-vgg "
             "averaged over the mask. Cameras whose mask is empty (no change yet) are left out of the dynamic-region averages.",
             ""]
    lines += table_lines
    if scene in PAPER:
        lines += ["", "Reference rows from the ODE-GS paper (their Stage 1 and runs; not under this protocol): "
                  + "; ".join(f"{m} {v[0]:.2f} / {v[1]:.4f} / {v[2]:.4f}" for m, v in PAPER[scene].items()) + " (PSNR / SSIM / LPIPS)."]
    lines += ["", "## Training PSNR curves", "",
              "Each learned run is scored at every 5% of its step budget. The x-axis is the optimizer step on the left "
              "and the training GPU-minutes on the right, with evaluation time excluded. Dashed lines show "
              "Deformable-GS, Static and CV. Raw data: `curves.csv`; Stage 1: `stage1_curve.csv`.", "",
              "Test cameras (display only):", "", "![test curves](curve_test.png)", "",
              "Inner validation cameras. Dotted lines are the [inner] runs, where these cameras are held out. Solid lines are the [full] "
              "runs, where they are in-sample targets.", "", "![val curves](curve_val.png)", "",
              "Stage 1 (Deformable-GS):", "", "![stage1](curve_stage1.png)", "", "Per-time PSNR on the test cameras:", "",
              "![per time](per_time_psnr.png)", "", "## Dynamic-region masks (examples, red overlay)", ""]
    lines += [f"![{m}]({m})" for m in masks]
    lines += ["", "## Videos", "", f"- `../videos/{scene}_eval.mp4`: every test camera at its own pose and time; "
              "GT / Deform-GS / Static / CV / ODE-GS / JEPA, with per-frame PSNR.",
              f"- `../videos/{scene}_sweep.mp4`: one fixed test camera with t swept over [0, 1]. Inside the prefix every "
              "method shows Stage 1; after it, each method shows its forecast."]
    if test:
        best = max(test, key=lambda n: test[n]["psnr"])
        lines += ["", "## Quick reading (auto)", "",
                  f"- Best full-image PSNR on the test cameras among the learned stage-2 runs: **{best}** ({test[best]['psnr']:.2f})."]
        if base:
            st, dq = base["full"]["static"], base["full"]["deform_query"]
            for n, r in test.items():
                lines.append(f"- {n}: {r['psnr'] - st['psnr']:+.2f} dB vs Static, {r['psnr'] - dq['psnr']:+.2f} dB vs Deformable-GS query; "
                             f"dynamic region {r.get('dyn_psnr', float('nan')) - st.get('dyn_psnr', float('nan')):+.2f} dB vs Static.")
    open(os.path.join(F, "report.md"), "w").write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--labels", default="{}", help="JSON {run_name: label}")
    ap.add_argument("--dt", type=float, default=None, help="prefix frame spacing (time units), for the config table")
    ap.add_argument("--write_report", action="store_true", help="also write <root>/fair/report.md")
    args = ap.parse_args()
    F = os.path.join(args.root, "fair")
    scene = os.path.basename(args.root.rstrip("/"))
    labels = json.loads(args.labels)
    if args.dt is None:
        args.dt = (load(os.path.join(F, "configs", "scene.json")) or {}).get("dt")
    runs = {os.path.basename(os.path.dirname(p)): load(p) for p in sorted(glob.glob(os.path.join(F, "runs", "*", "metrics.json")))}
    base = load(os.path.join(F, "baselines", "metrics.json"))
    L, summary, curves_pt = [], {}, {}

    def mode_of(r):
        return "rollout" if r["method"] == "jepa" else "default"

    # ------------------------------------------------------------ config table
    L += ["## Stage-2 configuration (every variable)", "",
          "| run | method | split | params | optimizer steps | Gaussian samples/step | observation window | "
          "train horizon | optimizer | LR peak | schedule | weight decay | grad clip | seed | train GPU-min (A100) |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in runs.items():
        c = r["cfg"]
        if r["method"] == "jepa":
            obs = f"{c['context_len']} Stage-1 frames, stride {c['context_stride']}"
            hor = f"≤ {c['max_horizon']} frames"
            if args.dt:
                obs += f" (span {(c['context_len'] - 1) * c['context_stride'] * args.dt:.4f})"
                hor += f" (= {c['max_horizon'] * args.dt:.4f} time)"
            sched = f"warmup {c['warmup_frac']:.0%} + cosine → {c['min_lr_ratio']}×"
            wd = c["weight_decay"]
            spp = f"{c['batch_contexts']} ctx × {c['gaussians_per_step']} = {r['samples_per_step']}"
        else:
            obs = f"{c['obs_time_span']:.4f} time span, {c['obs_points']} points"
            hor = f"≤ {c['max_extrap_time_span']:.4f} time ({c['extrap_points']} pts)"
            sched = f"warmup {c['warmup_frac']:.0%} + cosine → {c['min_lr_ratio']}×"
            wd = c["weight_decay"]
            spp = f"{r['samples_per_step']}"
        L.append(f"| {name} | {r['method']} | {r['split']} | {r['params'] / 1e6:.2f}M | {r['steps']} | {spp} | {obs} | {hor} | "
                 f"AdamW | {c['lr']:g} | {sched} | {wd:g} | 1.0 | {r['seed']} | {r['train_sec'] / 60:.1f} |")

    # ------------------------------------------------------------ results
    for split, title in [("full", "Test: protocol-B evaluation cameras (t > split), forecast from the end of the prefix"),
                         ("inner", "Inner validation: prefix cameras inner_cut < t ≤ prefix end, forecast from inner_cut")]:
        L += ["", f"## {title}", "",
              "| method | PSNR | PSNR_img | SSIM | LPIPS | dyn PSNR | dyn SSIM | dyn LPIPS |", "|---|---|---|---|---|---|---|---|"]
        for name, r in runs.items():
            if r["split"] != split:
                continue
            res = r["results"][mode_of(r)]
            L.append(f"| **{labels.get(name, name)}** | {row(res, FULL + DYN)} |")
            summary[f"{split}/{name}"] = {k: res.get(k) for k in FULL + DYN}
            if split == "full":
                curves_pt[labels.get(name, name)] = per_time(res)
        if base:
            k, kr = base["selected_k"], base.get("selected_k_rigid")
            for key, lab in ([(f"rigid{kr}", f"Group-rigid (k={kr}, chosen on inner split)")] if kr else []) + [
                             (f"cv{k}", f"Constant velocity (k={k}, chosen on inner split)"), ("static", "Static (last prefix state)"),
                             ("deform_query", "Deformable-GS (Stage 1 queried at t)" if split == "full" else
                              "_Stage-1 fit at these times (in-sample for Stage 1, NOT a forecast)_")]:
                res = base[split][key]
                L.append(f"| {lab} | {row(res, FULL + DYN)} |")
                summary[f"{split}/{key}"] = {x: res.get(x) for x in FULL + DYN}
                if split == "full":
                    curves_pt[lab] = per_time(res)
            if split == "full":
                others = ", ".join(f"k={q}: {base['full'][f'cv{q}']['psnr']:.2f}" for q in [1, 2, 4, 8, 16] if f"cv{q}" in base["full"])
                L.append(f"| _CV, all k (display only): {others}_ | | | | | | | |")
    r30 = {os.path.basename(os.path.dirname(p)): load(p) for p in sorted(glob.glob(os.path.join(F, "runs_30k", "*", "metrics.json")))}
    if r30:
        L += ["", "## Earlier 30k-step runs and the LR check (same settings otherwise)", "",
              "Rows with split = inner are scored on the inner validation cameras; these rows alone drove the LR decision "
              "(3e-4 → 1e-3). Rows with split = full are scored on the test cameras and shown for display only.", "",
              "| run | split | LR | steps | PSNR | SSIM | LPIPS | dyn PSNR |", "|---|---|---|---|---|---|---|---|"]
        for name, r in r30.items():
            res = r["results"][mode_of(r)]
            L.append(f"| {name} | {r['split']} | {r['cfg']['lr']:g} | {r['steps']} | {row(res, ['psnr', 'ssim', 'lpips', 'dyn_psnr'])} |")
    open(os.path.join(F, "tables.md"), "w").write("\n".join(L) + "\n")
    if args.write_report:
        write_report(args.root, scene, F, L, runs, base)

    # ------------------------------------------------------------ curves
    allrows = []
    for name, r in runs.items():
        p = os.path.join(F, "runs", name, "curve.csv")
        if os.path.exists(p):
            for c in read_curve(p):
                allrows.append({"run": name, **c})
    if allrows:
        keys = sorted({k for r in allrows for k in r}, key=lambda k: (k != "run", k != "step", k))
        with open(os.path.join(F, "curves.csv"), "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=keys)
            w.writeheader()
            w.writerows(allrows)
    s1 = stage1_curve(f"logs/stage1_{scene}.log") if os.path.exists(f"logs/stage1_{scene}.log") else []
    if s1:
        with open(os.path.join(F, "stage1_curve.csv"), "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(s1[0]))
            w.writeheader()
            w.writerows(s1)
    json.dump({"summary": summary, "per_time": curves_pt}, open(os.path.join(F, "summary.json"), "w"), indent=2)
    print("\n".join(L))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    ref_split = {"val": "inner", "test": "full"}
    for which in ["val", "test"]:
        fig, axes = plt.subplots(2, 2, figsize=(13, 8))
        for ci, metric in enumerate(["psnr", "dyn_psnr"]):
            for xi, (xkey, xlabel) in enumerate([("step", "optimizer step"), ("train_sec", "train GPU-minutes (A100)")]):
                ax = axes[ci, xi]
                for name, r in runs.items():
                    rs = [c for c in allrows if c["run"] == name and f"{which}_{metric}" in c]
                    if not rs:
                        continue
                    x = [c[xkey] / (60 if xkey == "train_sec" else 1) for c in rs]
                    col = "tab:red" if "lr" in name else {"jepa": "tab:blue", "odegs": "tab:orange"}[r["method"]]
                    ax.plot(x, [c[f"{which}_{metric}"] for c in rs], marker="o", ms=3, lw=1.8, color=col,
                            ls="-" if r["split"] == "full" else ":", label=f"{labels.get(name, name)} [{r['split']}]")
                if base:
                    k = base["selected_k"]
                    for key, lab, col in [("deform_query", "Deformable-GS", "gray"), ("static", "Static", "black"),
                                          (f"cv{k}", f"CV k={k}", "tab:brown")]:
                        v = base[ref_split[which]][key].get(metric)
                        if v is not None:
                            ax.axhline(v, color=col, ls="--", lw=1, label=lab)
                ax.set_xlabel(xlabel)
                ax.set_ylabel(("dynamic-region " if metric == "dyn_psnr" else "") + "PSNR (dB)")
                ax.grid(alpha=0.3)
        axes[0, 0].legend(fontsize=7)
        title = ("inner validation cameras (forecast from t = inner_cut; held out for [inner] runs, in-sample targets for [full] runs)"
                 if which == "val" else "test cameras t > split (display only, never used for decisions)")
        fig.suptitle(f"{scene}: stage-2 training curves on {title}", fontsize=10)
        fig.tight_layout()
        fig.savefig(os.path.join(F, f"curve_{which}.png"), dpi=130)
        plt.close(fig)
    if s1:
        fig, ax = plt.subplots(figsize=(7, 4))
        ax.plot([r["iter"] for r in s1], [r["train_psnr"] for r in s1], marker="o", ms=3, label="prefix (train) cameras: reconstruction")
        ax.plot([r["iter"] for r in s1], [r["test_psnr"] for r in s1], marker="o", ms=3, label="t > split cameras: Deformable-GS queried")
        ax.set_xlabel("Stage-1 iteration")
        ax.set_ylabel("PSNR (dB, ODE-GS training_report)")
        ax.set_title(f"{scene}: Stage 1 (Deformable-GS) PSNR")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
        fig.tight_layout()
        fig.savefig(os.path.join(F, "curve_stage1.png"), dpi=130)
        plt.close(fig)
    if curves_pt:
        fig, ax = plt.subplots(figsize=(8, 4.5))
        for lab, c in curves_pt.items():
            ts = sorted(c)
            ax.plot(ts, [c[t] for t in ts], marker="o", ms=3, label=lab)
        ax.set_xlabel("time t")
        ax.set_ylabel("PSNR (dB)")
        ax.set_title(f"{scene}: per-time PSNR on the test cameras")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(os.path.join(F, "per_time_psnr.png"), dpi=130)


if __name__ == "__main__":
    main()
